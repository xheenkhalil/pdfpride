def get_polished_description(tool):
    num = tool.get("number", 0)
    name = tool.get("name", "")
    op = tool.get("operation", "")
    cat = tool.get("category", "")

    if num in BESPOKE_DESCRIPTIONS:
        return BESPOKE_DESCRIPTIONS[num]

    # For any tool not explicitly listed, generate a clean, natural sentence
    nl = name.lower()
    if nl.startswith("pdf to "):
        target = name[7:].strip()
        return f"Convert PDF documents into {target} format with preserved content and formatting."
    if " to pdf" in nl:
        src = name.split(" to pdf")[0].strip()
        return f"Convert {src} files into standardized, high-quality PDF documents."
    if " to " in nl:
        parts = name.split(" to ")
        return f"Convert {parts[0].strip()} files into {parts[1].strip()} format seamlessly."
    if nl.startswith("merge "):
        return f"Combine multiple {name[6:].strip()} into a single consolidated file."
    if nl.startswith("split "):
        return f"Divide and separate {name[6:].strip()} into individual sections or files."
    if nl.startswith("compress "):
        return f"Reduce {name[9:].strip()} file size significantly while retaining high visual quality."
    if nl.startswith("batch "):
        return f"Process multiple {name[6:].strip()} files simultaneously in a single automated queue."
    
    return f"Professional {nl} utility for fast, accurate document processing."

